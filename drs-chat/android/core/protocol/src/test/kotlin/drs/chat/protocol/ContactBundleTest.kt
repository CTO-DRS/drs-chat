package drs.chat.protocol

import org.junit.jupiter.api.Assertions.assertArrayEquals
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNotEquals
import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Test

class ContactBundleTest {
    private fun bundle(withOtk: Boolean = true): ContactBundle =
        ContactBundle(
            ed25519Pub = ByteArray(32) { it.toByte() },
            x25519Pub = ByteArray(32) { (it + 1).toByte() },
            signedPreKeyId = 1,
            signedPreKeyPub = ByteArray(32) { (it + 2).toByte() },
            signedPreKeySig = ByteArray(64) { (it + 3).toByte() },
            oneTimePreKeyId = if (withOtk) 2 else null,
            oneTimePreKeyPub = if (withOtk) ByteArray(32) { (it + 4).toByte() } else null,
            kyberPreKeyId = 3,
            kyberPreKeyPub = ByteArray(32) { (it + 5).toByte() },
            kyberPreKeySig = ByteArray(64) { (it + 6).toByte() },
        )

    // MACHINE-CAPTURED golden vector — do not hand-edit. Generated by running
    // the real ContactBundleCodec encoder on the fixed fixture (kotlinx-cbor
    // 1.9.0, definite-length + byte-string). If a library upgrade changes ANY
    // byte, this strict equality fails.
    private val goldenBundleHex: String =
        "aa6265645820000102030405060708090a0b0c0d0e0f10111213141516" +
            "1718191a1b1c1d1e1f62783258200102030405060708090a0b0c0d0e0f" +
            "101112131415161718191a1b1c1d1e1f2064737069640163737070582002" +
            "030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f" +
            "2021637370735840030405060708090a0b0c0d0e0f1011121314151617" +
            "18191a1b1c1d1e1f202122232425262728292a2b2c2d2e2f3031323334" +
            "35363738393a3b3c3d3e3f404142646f74696402636f74705820040506" +
            "0708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f20212223" +
            "646b70696403636b7070582005060708090a0b0c0d0e0f101112131415" +
            "161718191a1b1c1d1e1f2021222324636b70735840060708090a0b0c0d" +
            "0e0f101112131415161718191a1b1c1d1e1f202122232425262728292a2b" +
            "2c2d2e2f303132333435363738393a3b3c3d3e3f404142434445"

    @Test fun `frozen golden vector — strict byte equality`() {
        val actual = ContactBundleCodec.encode(bundle()).joinToString("") { "%02x".format(it) }
        assertEquals(goldenBundleHex, actual, "ContactBundle CBOR encoding drifted")
    }

    @Test fun `round-trips through CBOR`() {
        val b = bundle()
        assertEquals(b, ContactBundleCodec.decode(ContactBundleCodec.encode(b)))
    }

    @Test fun `encode decode encode is stable`() {
        val b = bundle()
        val once = ContactBundleCodec.encode(b)
        assertArrayEquals(once, ContactBundleCodec.encode(ContactBundleCodec.decode(once)))
    }

    @Test fun `OTK-less bundle (signed-prekey-only X3DH fallback) round-trips`() {
        val b = bundle(withOtk = false)
        val d = ContactBundleCodec.decode(ContactBundleCodec.encode(b))
        assertEquals(null, d.oneTimePreKeyId)
        assertEquals(null, d.oneTimePreKeyPub)
    }

    @Test fun `OTK id+pub must both be null or both non-null`() {
        assertThrows(IllegalArgumentException::class.java) {
            bundle().copy(oneTimePreKeyId = null, oneTimePreKeyPub = ByteArray(32))
        }
    }

    // Tamper at a KNOWN OFFSET inside the signedPreKeySig region. The golden
    // hex shows the sig (64 bytes 0x03..0x45) starts at byte offset 125 (after
    // the map header + 5 fields + the "sps" key + the 58 40 bstr-64 prefix).
    // The test asserts the byte at offset 125 IS the first sig byte, then flips
    // it and asserts the decoded sig differs.
    @Test fun `tampered signed-prekey sig at known offset`() {
        val encoded = ContactBundleCodec.encode(bundle())
        // The first sig byte (0x03 = 3+0 = the first byte of signedPreKeySig)
        // lives at offset 125 in the golden vector.
        val sigOffset = 125
        assertEquals(0x03.toByte(), encoded[sigOffset], "sig byte not at expected offset $sigOffset")
        val tampered = encoded.copyOf()
        tampered[sigOffset] = (tampered[sigOffset].toInt() xor 0x01).toByte()
        val decoded = ContactBundleCodec.decode(tampered)
        assertNotEquals(true, decoded.signedPreKeySig.contentEquals(bundle().signedPreKeySig))
    }

    @Test fun `field size validation rejects bad ed25519 pub`() {
        assertThrows(IllegalArgumentException::class.java) {
            bundle().copy(ed25519Pub = ByteArray(31))
        }
    }
}
